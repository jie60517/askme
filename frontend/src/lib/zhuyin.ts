/**
 * 注音 → 英文按鍵的還原(搜尋名字時,注音模式下打出來的符號也能搜到英文帳號)。
 *
 * ⚠️ 瀏覽器**沒有任何 API 能切輸入法**(ime-mode 早就作廢了)—— 真正做得到的
 * 是「把注音打出來的字還原成他實際按下的鍵」:標準注音鍵盤(大千式)每個
 * 注音符號對應**固定一顆鍵**,使用者想打 jacky、輸入法卻吐出「ㄨㄇㄏㄜㄗ」,
 * 反查回去就是 jacky。搜尋框的 onChange 過一層這個,注音模式下照樣搜得到人。
 *
 * - 只動注音符號(U+3105–U+312F)與四個調號 —— **中文字原樣保留**,
 *   搜「小明」還是搜得到小明。
 * - 對照表是大千式(Windows 微軟注音的預設鍵盤),倚天/許氏那些少數派不管。
 */

/** 大千式(標準)注音鍵盤:符號 → 按鍵。 */
const ZHUYIN_TO_KEY: Record<string, string> = {
  'ㄅ': '1',
  'ㄉ': '2',
  'ˇ': '3',
  'ˋ': '4',
  'ㄓ': '5',
  'ˊ': '6',
  '˙': '7',
  'ㄚ': '8',
  'ㄞ': '9',
  'ㄢ': '0',
  'ㄦ': '-',
  'ㄆ': 'q',
  'ㄊ': 'w',
  'ㄍ': 'e',
  'ㄐ': 'r',
  'ㄔ': 't',
  'ㄗ': 'y',
  'ㄧ': 'u',
  'ㄛ': 'i',
  'ㄟ': 'o',
  'ㄣ': 'p',
  'ㄇ': 'a',
  'ㄋ': 's',
  'ㄎ': 'd',
  'ㄑ': 'f',
  'ㄕ': 'g',
  'ㄘ': 'h',
  'ㄨ': 'j',
  'ㄜ': 'k',
  'ㄠ': 'l',
  'ㄤ': ';',
  'ㄈ': 'z',
  'ㄌ': 'x',
  'ㄏ': 'c',
  'ㄒ': 'v',
  'ㄖ': 'b',
  'ㄙ': 'n',
  'ㄩ': 'm',
  'ㄝ': ',',
  'ㄡ': '.',
  'ㄥ': '/',
};

export function fromZhuyin(text: string): string {
  let out = '';
  for (const ch of text) out += ZHUYIN_TO_KEY[ch] ?? ch;
  return out;
}
