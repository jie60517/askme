const KEY = 't100_folder_icons';

export function readFolderIcons(): Record<string, string> {
  return (
    readJson(KEY, (value) =>
      value && typeof value === 'object' ? (value as Record<string, string>) : null,
    ) ?? {}
  );
}

export function writeFolderIcons(map: Record<string, string>) {
  writeJson(KEY, map);
}

/**
 * 沒選過、或選了一個已經不存在的 key,退回 `fallback`(預設是資料夾)。
 *
 * `fallback` 是給 Personal / Shared 用的:它們也能挑圖示,但沒挑的時候
 * 該是自己專屬那顆(人 / 公司),不是一個資料夾 —— 那會讓它們看起來
 * 像是多出來的兩個資料夾。
 */
export function folderIcon(key: string | undefined, fallback?: LucideIcon): LucideIcon {
  return FOLDER_ICONS.find((i) => i.key === key)?.icon ?? fallback ?? FOLDER_ICONS[0].icon;
}
