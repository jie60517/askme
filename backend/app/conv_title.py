"""沒有自訂標題時,一組對話要顯示成什麼:第一則問題的重點,不是原文。

整句長問題直接當標題會撐壞側邊欄與搜尋面板。

## 為什麼是規則而不是叫模型摘要

切到第一個標點通常就已經很好讀:

    請把這三筆資料整理成 Excel 給我:品號 0012345 數量 3、品號…(99 字)
      → 請把這三筆資料整理成 Excel 給我(19 字)
    這支程式的標準流程是什麼?(請給檔名,例如 orders.py)(32 字)
      → 這支程式的標準流程是什麼(12 字)

第一個標點在很後面的只能硬截。叫模型摘要品質會更好,但那是**每組對話多一個
計費的 claude 行程**、要新欄位存、舊對話要回填。使用者自己改的名字永遠優先。

## 這裡**不存**,每次回清單時算

沒有資料庫遷移、沒有回填,規則改了舊對話立刻跟著變。代價是每次回清單多跑一遍
字串處理 —— 量級是「幾十組對話 × 一次 split」,可以忽略。
"""

from __future__ import annotations

import re

#: 切在哪裡 —— 中英文的「一句話結束」或「前言結束」。
#:
#: ⚠️ 頓號(、)**不在裡面**:它連的是並列的東西(「品號、數量、日期」),
#: 切在那裡會把一句話砍成沒頭沒尾的一截。冒號在裡面,因為中文的問句很常是
#: 「請幫我做某件事:細節細節細節」——冒號前面那半正好就是重點。
#:
#: ⚠️ **全形字一律用 `\u` 跳脫寫,不要直接打。** 全形與半形的標點肉眼分不出來,
#: 編輯器或複製貼上把全形存成半形的話,標題就不會在全形標點那裡切。
#:
#: ⚠️ **半形逗號、冒號要看前後文**:它們常常是資料的一部分 ——
#: 「14:30 的排程沒跑」不該切成「14」、「https://… 打不開」不該切成「https」、
#: 「abc100, abc101 差在哪」不該切成「abc100」。所以前後都是英數字(14:30、1,000、
#: abc100, abc101)或冒號緊接著 /(https://)的時候不切;前面是中文(「給我:品號…」)、
#: 冒號後面空一格再接說明(「Error: connection refused」)照切。
#: 取捨:英文句子的逗號(「Hi, can you help…」)也因此不切,標題會是硬截的整句 ——
#: 整句截斷也比只剩一個「Hi」有資訊量。
_BREAK = re.compile(
    r"[\uFF0C\u3002\uFF1B\uFF1A\uFF1F\uFF01;!]"  # 全形的逗號、句號、分號、冒號、問號、驚嘆號,加半形 ; !
    # 半形問號:前後都像網址(a?id=3)的是查詢字串,不切;「料號?A001」前面是中文,照切
    r"|\?(?![A-Za-z0-9])|(?<![A-Za-z0-9/._-])\?"
    r"|(?<![A-Za-z0-9])[,:]"  # 半形 , : 前面不是英數字 → 斷點
    r"|,(?!\s*[A-Za-z0-9])"  # 半形逗號:後面(可以隔空白)不是英數字 → 斷點(abc100, abc101 不切)
    r"|:(?![A-Za-z0-9/])"  # 半形冒號:緊接著不是英數字或 / → 斷點(14:30、https:// 不切;「Error: …」照切)
)

#: 切完還是太長就硬截。24 個字是照側邊欄量的:展開的側邊欄一列放得下約 24 個中文字,
#: 再長的部分本來就會被省略號吃掉,留著只是讓搜尋面板那一列更難讀。
TITLE_LIMIT = 24


def summarize_title(question: str) -> str:
    """把一則問題變成一行標題。

    規則只有三步:取第一行 → 切到第一個標點 → 還是太長就截斷加刪節號。
    空字串進來就空字串出去(呼叫端自己決定要不要退回別的東西)。
    """
    first_line = question.strip().splitlines()[0].strip() if question.strip() else ""
    if not first_line:
        return ""

    head = _BREAK.split(first_line, maxsplit=1)[0].strip()
    # 整行開頭就是標點(「?怎麼會這樣」)—— 切出來是空的,那就用原本那一行
    if not head:
        head = first_line

    if len(head) > TITLE_LIMIT:
        return head[:TITLE_LIMIT] + "…"
    return head

